function formatBytes(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}

function printMemorySnapshot(label) {
  const mem = process.memoryUsage();
  console.log(`[Memory: ${label}]`);
  console.log(` - RSS (Resident Set Size - total OS RAM): ${formatBytes(mem.rss)}`);
  console.log(` - Heap Total (V8 allocated memory):       ${formatBytes(mem.heapTotal)}`);
  console.log(` - Heap Used (Active JavaScript objects):   ${formatBytes(mem.heapUsed)}`);
  console.log(` - External (C++ bound buffers, Node core): ${formatBytes(mem.external)}`);
  console.log(` - ArrayBuffers (TypedArrays & Buffers):    ${formatBytes(mem.arrayBuffers)}\n`);
}

printMemorySnapshot("Initial Process Startup");


