console.log("--- 2. LEAK PATTERN: TIMERS & INTERVALS IN REACT/NODE ---");

/**
 * ❌ BUGGY REACT PATTERN:
 * useEffect(() => {
 *   const interval = setInterval(() => {
 *     fetchLiveStockPrices();
 *   }, 1000);
 *   // 💥 MISSING CLEANUP! If the component unmounts and remounts 10 times,
 *   // there are now 10 intervals running simultaneously, leaking memory and CPU!
 * }, []);
 *
 * ✅ PROPER REACT PATTERN:
 * useEffect(() => {
 *   const interval = setInterval(fetchLiveStockPrices, 1000);
 *   return () => clearInterval(interval); // Cleaned up when unmounted!
 * }, []);
 */

class SafePollingService {
  constructor() {
    this.timerId = null;
    this.pollCount = 0;
  }

  start(intervalMs) {
    if (this.timerId) return; // Prevent duplicate timers
    this.timerId = setInterval(() => {
      this.pollCount++;
      if (this.pollCount >= 3) {
        this.stop(); // Safe programmatic termination
      }
    }, intervalMs);
  }

  stop() {
    if (this.timerId) {
      clearInterval(this.timerId);
      this.timerId = null;
      console.log(`[SafePollingService] Interval stopped and cleared cleanly.`);
    }
  }
}

const poller = new SafePollingService();
poller.start(50);


