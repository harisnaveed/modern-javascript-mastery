console.log("\n--- 4. LEAK PATTERN: UNBOUNDED IN-MEMORY CACHE ---");

/**
 * ❌ DANGEROUS NODE.JS PATTERN:
 * const apiCache = {};
 * app.get('/user/:id', (req, res) => {
 *   if (!apiCache[req.params.id]) {
 *     apiCache[req.params.id] = fetchUserFromDB(req.params.id); // 💥 GROWS FOREVER!
 *   }
 *   res.json(apiCache[req.params.id]);
 * });
 *
 * If you have 5,000,000 unique user IDs, `apiCache` will consume all heap RAM and crash!
 *
 * ✅ MODERN SOLUTION: LRU (Least Recently Used) Cache with Max Size Capacity
 */

class LRUCache {
  constructor(maxCapacity = 3) {
    this.capacity = maxCapacity;
    this.cache = new Map(); // Map preserves insertion order!
  }

  get(key) {
    if (!this.cache.has(key)) return null;
    // Refresh position to mark as recently used
    const value = this.cache.get(key);
    this.cache.delete(key);
    this.cache.set(key, value);
    return value;
  }

  set(key, value) {
    if (this.cache.has(key)) {
      this.cache.delete(key);
    } else if (this.cache.size >= this.capacity) {
      // Evict the oldest entry (the first item in Map iterator)
      const oldestKey = this.cache.keys().next().value;
      console.log(`[LRU Cache] Evicting least recently used key: "${oldestKey}" to protect memory!`);
      this.cache.delete(oldestKey);
    }
    this.cache.set(key, value);
  }

  get size() {
    return this.cache.size;
  }
}

const boundedCache = new LRUCache(3);
boundedCache.set("user:1", { name: "Haris Ali" });
boundedCache.set("user:2", { name: "Ayesha Khan" });
boundedCache.set("user:3", { name: "Usman Tariq" });
console.log(`[LRU Cache] Size after 3 entries: ${boundedCache.size}`);

// Adding 4th item forces eviction of oldest key ("user:1")
boundedCache.set("user:4", { name: "Zainab Bibi" });
console.log(`[LRU Cache] Querying evicted user:1: ${boundedCache.get("user:1")}`); // null
console.log(`[LRU Cache] Querying active user:4:  ${boundedCache.get("user:4").name}`);


