const { EventEmitter } = require("events");

class WebSocketHub extends EventEmitter {}
const chatHub = new WebSocketHub();

// Set max listeners warning threshold (default is 10)
chatHub.setMaxListeners(10);

class UserChatSession {
  constructor(userId) {
    this.userId = userId;
    // Bound listener reference to ensure correct removal
    this.messageHandler = this.onNewMessage.bind(this);
    this.connect();
  }

  connect() {
    // Register listener on shared hub
    chatHub.on("message", this.messageHandler);
    console.log(`[Session: ${this.userId}] Connected (Listeners count: ${chatHub.listenerCount("message")})`);
  }

  onNewMessage(msg) {
    // Process message
  }

  disconnect() {
    // ✅ CRITICAL: Always remove listener when user logs out or leaves room!
    // Without this, chatHub holds a permanent reference to this instance,
    // preventing V8 Garbage Collector from reclaiming UserChatSession!
    chatHub.removeListener("message", this.messageHandler);
    console.log(`[Session: ${this.userId}] Disconnected & Cleaned up (Listeners remaining: ${chatHub.listenerCount("message")})`);
  }
}

const session1 = new UserChatSession("User_101");
const session2 = new UserChatSession("User_102");

// Disconnecting cleans up listeners completely
session1.disconnect();
session2.disconnect();


