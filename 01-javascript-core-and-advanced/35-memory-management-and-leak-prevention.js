console.log("\n--- 5. WEAKMAP & WEAKSET FOR LEAK-FREE METADATA STORAGE ---");

/**
 * Standard Map vs WeakMap:
 * - Map: Holds "strong" references to keys. Even if the key object is set to null,
 *   the Map still retains it in memory.
 * - WeakMap: Holds "weak" references to keys. When the key object has no other
 *   active references, V8 Garbage Collector reclaims it automatically!
 */

// 1. Standard Map retains reference:
const strongMap = new Map();
let domElementSim = { id: "modal-button", tag: "BUTTON" };
strongMap.set(domElementSim, { clickCount: 42 });

// 2. WeakMap allows garbage collection:
const weakMetadataMap = new WeakMap();
let userRef = { id: 999, username: "temporary_session" };
weakMetadataMap.set(userRef, { lastActive: Date.now(), token: "jwt_abc_123" });

console.log("WeakMap has userRef before nulling:", weakMetadataMap.has(userRef)); // true

// When the user logs out or the DOM element is unmounted:
userRef = null; 
// ✅ In V8's next GC cycle, the memory allocated for userRef and its WeakMap entry
// is automatically reclaimed! There is NO memory leak!


