/**
 * ============================================================================
 * MODULE 35: Memory Management, V8 Garbage Collection & Memory Leaks in React/Node
 * ============================================================================
 *
 * 1. THE "WHY" & HISTORICAL BACKGROUND
 * ----------------------------------------------------------------------------
 * In the early days of JavaScript (ES3 / Internet Explorer 6 era), memory 
 * management was notorious for causing browser freezes and tab crashes. Older 
 * browsers relied on primitive "Reference Counting" algorithms that failed 
 * miserably when circular references occurred (e.g., a JavaScript object 
 * referencing a DOM element, and that DOM element referencing the JavaScript object).
 *
 * Furthermore, modern JavaScript runs in two radically different environments:
 * 1. Browsers (Single Page Applications like React & Next.js): Users keep single-page 
 *    apps open for days or weeks. Uncleaned event listeners, uncleared timers, and 
 *    detached DOM nodes gradually consume gigabytes of RAM, causing lag and crashes.
 * 2. Node.js & Next.js Server Runtimes: Unlike traditional server environments, 
 *    Node.js runs as a SINGLE, long-running persistent daemon process. A minor 
 *    memory leak of just 10 KB per HTTP request will inevitably crash a production 
 *    server under 100,000 requests with:
 *    "FATAL ERROR: Ineffective mark-compacts near heap limit Allocation failed - JavaScript heap out of memory"
 *
 * Understanding how the V8 engine allocates memory and how the Garbage Collector (GC) 
 * works is essential for building scalable, enterprise-grade fullstack applications.
 *
 *
 * 2. PHP / LARAVEL ANALOGY
 * ----------------------------------------------------------------------------
 * - PHP's "Share-Nothing" Lifecycle:
 *   In classic PHP (Apache mod_php or PHP-FPM), every HTTP request is completely isolated.
 *   The PHP engine boots, processes the request, sends the response, and IMMEDIATELY 
 *   terminates and destroys the entire memory space (Zend Memory Manager frees everything).
 *   Developers rarely had to worry about long-running memory accumulation because 
 *   every variable is wiped clean at the end of the request script!
 *
 * - The Node.js / Next.js Paradigm:
 *   Node.js is a PERSISTENT process. Module-level variables, database pools, singleton 
 *   services, and event emitters stay alive across thousands of concurrent incoming requests.
 *   If you append user data or request tokens to a module-scoped array `const userCache = []`, 
 *   that memory will NEVER be freed unless manually pruned!
 *
 * - Laravel Octane / Swoole Comparison:
 *   Notice that when modern PHP introduced "Laravel Octane" (powered by Swoole or RoadRunner 
 *   to keep the PHP application resident in RAM for speed), Laravel developers suddenly 
 *   faced the exact same memory leak bugs that Node.js developers face: static properties 
 *   retaining request state, singleton memory leaks, and unbounded cache growth.
 *
 *
 * 3. V8 ENGINE MEMORY ARCHITECTURE & GARBAGE COLLECTION
 * ----------------------------------------------------------------------------
 * A running Node.js or browser process organizes memory into distinct spaces:
 *
 * A. Stack:
 *    Fast, fixed-size memory storing primitive values (numbers, booleans) and pointer 
 *    references to heap objects. Cleaned up immediately when a function execution context exits.
 *
 * B. Heap:
 *    Dynamic memory pool storing complex reference types (Objects, Arrays, Closures, Functions):
 *    1. Young Generation (Nursery & Intermediate):
 *       - Where newly created objects are first allocated.
 *       - Cleaned frequently by the "Scavenger" GC algorithm (Cheney's copying algorithm).
 *       - Extremely fast (1ms - 3ms pause).
 *    2. Old Generation (Old Pointer & Old Data Space):
 *       - Objects that survive 2 Scavenge cycles get promoted ("tenured") to Old Space.
 *       - Cleaned by the Major GC using the "Mark-Sweep-Compact" (Orinoco) algorithm.
 *       - If Old Space fills up, Node.js triggers heavy GC pauses or Out-Of-Memory (OOM) fatal crashes.
 *    3. Large Object Space:
 *       - Holds objects larger than the allocation capacity of other spaces to avoid moving them.
 *    4. Code Space:
 *       - Stores JIT-compiled machine code instructions generated by V8's Ignition & TurboFan.
 *
 * How Modern V8 Garbage Collection Works: "Mark and Sweep"
 * V8 starts from a "Root Set" (Global object, active call stack frames, DOM tree root).
 * It traverses every reachable reference recursively:
 * - REACHABLE: Any object connected via a chain of references to the root is marked "alive".
 * - UNREACHABLE: Any isolated object or circular reference with no path to the root is "garbage".
 * - SWEEP & COMPACT: Memory occupied by unreachable objects is freed and fragmented memory is compacted.
 *
 *
 * 4. THE 5 CLASSIC MEMORY LEAKS IN REACT & NODE.JS
 * ----------------------------------------------------------------------------
 * Leak 1: Uncleared Timers & Intervals (`setInterval` / `setTimeout`)
 *         In React `useEffect`, failing to return a cleanup function leaves the interval running.
 * Leak 2: Forgotten Event Listeners & EventEmitters
 *         Registering `window.addEventListener` or `emitter.on()` without `removeEventListener`.
 * Leak 3: Closures Retaining Oversized Lexical Scopes
 *         Inner functions holding onto large arrays or buffers from parent scope indefinitely.
 * Leak 4: Detached DOM Nodes (Browser)
 *         Storing references to DOM elements in a JS array or object after the element is removed from DOM.
 * Leak 5: Unbounded In-Memory Caches & Accidental Globals
 *         Module-level `const cache = {}` that grows indefinitely without an LRU eviction strategy.
 *
 * Solution: WeakMap & WeakSet
 * WeakMap and WeakSet hold "weak" references to objects. If an object has no OTHER strong 
 * references anywhere in your application, V8 Garbage Collector will automatically reclaim 
 * the object and remove it from the WeakMap/WeakSet!
 * ============================================================================
 */

